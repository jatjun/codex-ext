export function prompt(kind: Kind, phase: Phase) {
  return kind === "view"
    ? phase === "guided"
      ? "从前面正对着看，看到的数字是几？"
      : phase === "practice"
        ? "不转动检查：前面是1，后面的数字是几？"
        : "新纸盒：右面是1，左面的数字是几？"
    : phase === "guided"
      ? "中央数字1的对面是哪一个数字？"
      : phase === "practice"
        ? "上面数字5的对面是哪一个数字？"
        : "新纸盒：右面数字1的对面是哪一个数字？";
}
